export type TextKey = keyof typeof fr;

const en: Record<TextKey, string> = { ...fr };

const tables = { fr, en } as const;
export type Lang = keyof typeof tables;

let current: Lang = 'fr';

export function setLang(lang: Lang): void {
  current = lang;
}

export function t(key: TextKey): string {
  return tables[current][key];
}

export function currentLang(): Lang {
  return current;
}

/** Text that follows the character's gender: `key_m` / `key_f` when written, the neutral key otherwise. */
export function tg(key: TextKey, gender: string): string {
  const table = tables[current] as Record<string, string>;
  return table[`${key}_${gender}`] ?? table[key] ?? key;
}

export function trophyName(id: string): string {
  return t(`trophy_${id}` as TextKey);
}

export function trophyKindText(kind: string): string {
  return t(`td_${kind}` as TextKey);
}

export function stageName(id: string): string {
  return t(`stage_${id}` as TextKey);
}

export function fatalText(kind: string, gender = 'n'): string {
  return tg(`fatal_${kind}` as TextKey, gender);
}

export function upgradeName(id: string): string {
  return t(`up_${id}` as TextKey);
}

export function upgradeEffect(id: string): string {
  return t(`fx_${id}` as TextKey);
}

export function helmetName(id: string): string {
  return t(`helmet_${id}` as TextKey);
}

export function layerName(id: string): string {
  return t(`layer_${id}` as TextKey);
}
